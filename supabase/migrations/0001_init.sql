-- ── Seeding helper: after inserting rows with explicit ids, bump the identity
-- sequences so future inserts don't collide. Service-role only.
create or replace function public.reset_id_sequences()
returns void language plpgsql security definer set search_path = public as
$$
begin
  perform setval(pg_get_serial_sequence('products', 'id'), greatest((select coalesce(max(id), 1) from products), 1));
  perform setval(pg_get_serial_sequence('product_variants', 'id'), greatest((select coalesce(max(id), 1) from product_variants), 1));
  perform setval(pg_get_serial_sequence('product_images', 'id'), greatest((select coalesce(max(id), 1) from product_images), 1));
  perform setval(pg_get_serial_sequence('collections', 'id'), greatest((select coalesce(max(id), 1) from collections), 1));
  perform setval(pg_get_serial_sequence('size_charts', 'id'), greatest((select coalesce(max(id), 1) from size_charts), 1));
end;
$$;
revoke all on function public.reset_id_sequences from public;
grant execute on function public.reset_id_sequences to service_role;

-- ── Typo-tolerant catalog search (used when Supabase mode is active) ─────────
create or replace function public.search_products(q text, max_results int default 12)
returns table (id bigint, handle text, title text, rank real)
language sql stable security definer set search_path = public as
$$
  select p.id, p.handle, p.title,
         (ts_rank(p.search, websearch_to_tsquery('simple', q)) +
          similarity(p.title, q))::real as rank
  from products p
  where p.published_at is not null
    and (p.search @@ websearch_to_tsquery('simple', q) or p.title % q)
  order by rank desc
  limit max_results;
$$;
grant execute on function public.search_products to anon, authenticated, service_role;
