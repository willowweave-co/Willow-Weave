create table public.products (
  id bigint generated by default as identity primary key,
  handle text not null unique,
  title text not null,
  description_html text not null default '',
  product_type text not null default '',
  fabrics text[] not null default '{}',
  tags text[] not null default '{}',
  vendor text not null default 'Willow Weave',
  published_at timestamptz,
  created_at timestamptz not null default now(),
  size_chart_id bigint references size_charts (id) on delete set null,
  search tsvector generated always as (
    setweight(to_tsvector('simple', coalesce(title, '')), 'A') ||
    setweight(to_tsvector('simple', coalesce(product_type, '')), 'B') ||
    setweight(to_tsvector('simple', array_to_string(tags, ' ')), 'B') ||
    setweight(to_tsvector('simple', array_to_string(fabrics, ' ')), 'B') ||
    setweight(to_tsvector('simple', coalesce(description_html, '')), 'C')
  ) stored
);
